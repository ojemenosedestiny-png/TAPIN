export function SiteIcon({ name, size = 18 }: { name: keyof typeof PATHS; size?: number }) {
  return (
    <svg width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={1.8} strokeLinecap="round" strokeLinejoin="round" aria-hidden>
      {PATHS[name]}
    </svg>
  );
}

const LABEL: Record<SocialNetwork, string> = { facebook: "Facebook", instagram: "Instagram", x: "X (Twitter)", linkedin: "LinkedIn", tiktok: "TikTok", youtube: "YouTube" };

/** TapIn's social pages, as round icon buttons. Nothing renders until at least one link is set in lib/site.ts. */
export function SocialLinks() {
  const links = (Object.entries(SOCIAL) as [SocialNetwork, string][]).filter(([, url]) => url);
  if (!links.length) return null;
  return (
    <ul className="social" aria-label="TapIn on social media">
      {links.map(([network, url]) => (
        <li key={network}>
          <a href={url} target="_blank" rel="noopener noreferrer me" aria-label={`TapIn on ${LABEL[network]}`} title={LABEL[network]}>
            <SiteIcon name={network} />
          </a>
        </li>
      ))}
    </ul>
  );
}
